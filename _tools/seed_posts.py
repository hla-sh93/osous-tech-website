# -*- coding: utf-8 -*-
"""
Seed the blog posts taken from the static index page.

    python _tools/seed_posts.py
    docker compose --profile tools run --rm cli wp eval-file /migration/posts.php

`blog.html` is a snapshot of the first page of the live blog: twelve posts with their
titles, dates, slugs and pictures, and pagination running to page nine. The bodies are not
in this repository — only the index was cloned — so the posts are seeded with their
headings and a note saying so, and the real text comes with the production import.

That is enough to turn the blog from a page of hardcoded cards into a real loop, which is
the thing that was wrong with it. Twelve real posts render the same grid the snapshot
shows, so `_tools/verify_wp.py` can keep checking it.
"""
import io
import json
import os
import re
import sys

from lxml import html as LH

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "_migration", "posts.php")

PLACEHOLDER = (
    "<!-- wp:paragraph -->\n<p>%s</p>\n<!-- /wp:paragraph -->"
)


def posts_from_index():
    doc = LH.parse(os.path.join(ROOT, "blog.html")).getroot()
    found = []

    for card in doc.xpath('//main//a[contains(@class,"blog-card")]'):
        href = card.get("href") or ""
        image = card.xpath(".//img")[0]
        date = " ".join(card.xpath('.//div[contains(@class,"t-r-sm")]')[0].text_content().split())
        title = " ".join(card.xpath(".//h2")[0].text_content().split())

        found.append({
            "slug": href[:-5] if href.endswith(".html") else href,
            "title": title,
            "date": date,
            "src": image.get("src"),
            "srcset": image.get("srcset") or "",
            "alt": image.get("alt") or "",
        })

    return found


PHP = """<?php
/**
 * Seed the blog posts from the static index page.
 *
 * Generated by _tools/seed_posts.py -- local development only. Run once:
 *
 *   docker compose --profile tools run --rm cli wp eval-file /migration/posts.php
 *
 * The pictures stay in the theme's uploads folder rather than going to the Media Library:
 * they are the exact files, at the exact sizes, that the reference page names, which is
 * what lets the blog grid go on being checked against it. A real import brings real
 * attachments and `osous_post_thumb()` prefers those.
 */

$posts = json_decode( <<<'JSON'
%(json)s
JSON
, true );

$done = 0;

foreach ( $posts as $item ) {
\t$existing = get_page_by_path( $item['slug'], OBJECT, 'post' );

\t$data = array(
\t\t'post_type'    => 'post',
\t\t'post_status'  => 'publish',
\t\t'post_name'    => $item['slug'],
\t\t'post_title'   => $item['title'],
\t\t'post_date'    => gmdate( 'Y-m-d H:i:s', strtotime( $item['date'] ) ),
\t\t'post_content' => $item['body'],
\t);
\tif ( $existing ) {
\t\t$data['ID'] = $existing->ID;
\t}

\t$id = wp_insert_post( wp_slash( $data ) );
\tif ( ! $id || is_wp_error( $id ) ) {
\t\tWP_CLI::warning( "could not save {$item['slug']}" );
\t\tcontinue;
\t}

\tupdate_post_meta( $id, '_osous_thumb', array(
\t\t'src'    => $item['src'],
\t\t'srcset' => $item['srcset'],
\t\t'alt'    => $item['alt'],
\t) );
\t$done++;
}

// WordPress's own Hello world! post is not one of ours and sorts to the front.
$hello = get_page_by_path( 'hello-world', OBJECT, 'post' );
if ( $hello ) {
\twp_delete_post( $hello->ID, true );
}

/*
 * Only now does /blog/ become the posts index. The seed deliberately leaves it unset
 * while the blog is still a section page, so that page can be verified like any other.
 */
$blog = get_page_by_path( 'blog', OBJECT, 'page' );
if ( $blog ) {
\tupdate_option( 'page_for_posts', $blog->ID );
}

update_option( 'posts_per_page', 12 );

WP_CLI::success( sprintf( '%%d posts, 12 to a page', $done ) );
"""


def main():
    posts = posts_from_index()
    for post in posts:
        post["body"] = PLACEHOLDER % (
            "The text of this post is on the live site and was not part of the clone. "
            "Importing the production posts replaces this."
        )

    text = PHP % {"json": json.dumps(posts, ensure_ascii=False, indent=1)}
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)

    print("wrote %s" % OUT)
    print("%d posts" % len(posts))
    for post in posts[:3]:
        print("  %-14s %s" % (post["date"], post["title"][:58]))
    print("  ...")


if __name__ == "__main__":
    main()
