# -*- coding: utf-8 -*-
"""
Write the section data into each page as blocks.

Generates `_migration/blocks.php`, which WP-CLI runs once:

    python _tools/gen_blocks.py
    docker compose --profile tools run --rm cli wp eval-file /migration/blocks.php

One `osous/section` block per top-level section, in order, which is what makes them
reorderable by dragging. The data is carried in the file rather than read from the theme:
the theme holds the renderer, the database holds the content, and the static pages at the
repository root remain the thing both are checked against.

`_tools/verify_wp.py` has to report zero differences afterwards. It is the only proof that
the migration moved the content without changing it.
"""
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from extract import ROOT, extract_all, walk  # noqa: E402

OUT = os.path.join(ROOT, "_migration", "blocks.php")

# A name for each section, so the editor's list reads as a page rather than as
# "Section, Section, Section". Matched in order: the first hit wins, so the most
# distinctive marker has to come first.
LABELS = [
    ("header-contents", "Page header"),
    ("list-scroll", "Pinned list"),
    ("split-section", "Split section"),
    ("card-overlapping-item", "Card stack"),
    ("swiper-container", "Industries carousel"),
    ("infinite-carousel", "Hero"),
    ("contact-form", "Contact form"),
    ("blog-card", "Blog list"),
    ("pagination-wrapper", "Pagination"),
    ("partner-card", "Partner logos"),
    ("partner-card-logo", "Partner logos"),
    ("rich-text-block", "Rich text"),
    ("feature-card", "Feature cards"),
    ("card-2", "Numbered cards"),
    ("card-5", "Highlight cards"),
    ("card-4", "Photo cards"),
    ("card-3", "Overlay cards"),
    ("card-1", "Cards"),
    ("list-item-tick", "Tick list"),
    ("list-item-bullet", "Bullet list"),
    ("modal", "Intro panel"),
    ("cell", "Columns"),
    # Late and deliberately broad: whatever is left is a heading with a paragraph beside
    # it, a lone heading, or a rule. Naming them is the difference between a page that
    # reads as a page in the list view and one that reads as "Section" forty times.
    ("grid-2", "Text pair"),
    ("heading", "Heading"),
    ("divider", "Divider"),
]


def classes_in(node):
    """Every class used anywhere under a node, as one set."""
    found = set()
    for item in walk([node]):
        found.update((item.get("c") or "").split())
        if item.get("t") == "rich":
            found.add("rich-text-block")
    return found


def label_for(node):
    present = classes_in(node)

    # The call to action is a heading in a bordered white panel, and nothing else is.
    if "top-tight" in present and "c-border-neutral" in present:
        return "Call to action"

    for marker, name in LABELS:
        if marker in present:
            return name

    return "Section"


PHP = """<?php
/**
 * Move the section data into the pages as blocks.
 *
 * Generated by _tools/gen_blocks.py -- local development only. Run once:
 *
 *   docker compose --profile tools run --rm cli wp eval-file /migration/blocks.php
 *
 * Rerunning it overwrites every page, which is how an experiment in the editor is undone
 * without reaching for a database snapshot.
 */

$pages = json_decode( <<<'JSON'
%(json)s
JSON
, true );

$done  = 0;
$bytes = 0;

foreach ( $pages as $slug => $sections ) {
\t$page = get_page_by_path( $slug, OBJECT, 'page' );
\tif ( ! $page ) {
\t\tWP_CLI::warning( "no page for {$slug}" );
\t\tcontinue;
\t}

\t$blocks = array();
\tforeach ( $sections as $section ) {
\t\t$blocks[] = array(
\t\t\t'blockName'    => 'osous/section',
\t\t\t'attrs'        => array(
\t\t\t\t'label' => $section['label'],
\t\t\t\t'nodes' => array( $section['node'] ),
\t\t\t),
\t\t\t'innerBlocks'  => array(),
\t\t\t'innerHTML'    => '',
\t\t\t'innerContent' => array(),
\t\t);
\t}

\t$content = serialize_blocks( $blocks );
\t$bytes  += strlen( $content );

\t/*
\t * Slashed, because wp_update_post() unslashes what it is given. The block delimiters
\t * are JSON, and serialize_blocks() escapes every & < > ' " in them as a %(bs)su
\t * sequence so the comment stays a comment -- pass that through unslashed and every
\t * backslash is eaten, leaving `u0026` in the middle of the words.
\t */
\twp_update_post( wp_slash( array(
\t\t'ID'           => $page->ID,
\t\t'post_content' => $content,
\t) ) );
\t$done++;
}

WP_CLI::success( sprintf( '%%d pages, %%s KB of block content', $done, number_format( $bytes / 1024 ) ) );
"""


def main():
    pages = extract_all()
    data = {
        slug: [{"label": label_for(node), "node": node} for node in nodes]
        for slug, nodes in sorted(pages.items())
    }

    text = PHP % {"bs": chr(92), "json": json.dumps(data, ensure_ascii=False)}
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)

    counts = {}
    for sections in data.values():
        for section in sections:
            counts[section["label"]] = counts.get(section["label"], 0) + 1

    print("wrote %s  (%.0f KB)" % (OUT, os.path.getsize(OUT) / 1024.0))
    print("%d pages, %d sections" % (len(data), sum(len(v) for v in data.values())))
    for name, count in sorted(counts.items(), key=lambda kv: -kv[1]):
        print("  %-22s %3d" % (name, count))


if __name__ == "__main__":
    main()
