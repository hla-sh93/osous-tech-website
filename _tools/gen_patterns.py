"""
Build the pattern library: one pattern per kind of section, and one starter per kind of page.

    python _tools/gen_patterns.py

Writes `theme/patterns/sections/*.php` and `theme/patterns/starters/*.php`. The theme
registers them from their headers (functions/patterns.php), the way WordPress registers a
theme's own patterns/ folder -- which it only scans one level deep, and this theme keeps
its sections a level down so they read apart from the page starters.

A section pattern is the way a page grows: it drops a real section onto the page -- a
heading, a grid, its cards -- with its shape already right, ready to have its words
changed. Each one is a real section lifted from a real reference page rather than a
hand-written stub, converted by _tools/gen_blocks.py exactly as the pages were, so the
inserter previews the design itself. The instance chosen for each kind is the one closest
to the median size, so the grid that lands on the page is a typical one rather than the
longest on the site.

A starter is the way a page begins: every section of a typical page of its kind, in
order. The editor offers the kinds when a new page is opened, sets the page's template
and lays the starter's sections down (theme/blocks/editor/page-kind.js). The page chosen
for a kind has the shape most pages of that kind share; where no two share one, it is the
page of median size. The kinds themselves are in _tools/kinds.py.

The files are indented one step per nested block, which WordPress does not need and a
person reading them does.
"""
