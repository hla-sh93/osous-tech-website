# -*- coding: utf-8 -*-
"""
Seed the Contact Form 7 form that the contact page's section points at.

    python _tools/seed_contact.py
    docker compose --profile tools run --rm cli wp eval-file /migration/contact.php

The live site's form is Contact Form 7 with Simple Cloudflare Turnstile, and the reference
page is CF7's own rendering of exactly these tags -- the same names, ids, sizes and
placeholders -- with the plugin's scaffolding stripped. The block data finds the form by
its title (see gen_blocks.CONTACT_FORM), so a form called "Contact" has to exist on every
install before /contact/ shows one. CF7's own sample form, which activation creates, is
retitled and reused rather than left beside it.

The widget goes after the submit button, with the tag, because that is where the live
site has it; the plugin's "add to all forms" option would put it before.

Cloudflare's always-pass test keys go in locally, so the widget renders and a submission
goes through without a real challenge. Production replaces them under Settings →
Cloudflare Turnstile, and nothing else changes. They are only written where the key is
still empty, so a real key is never overwritten.
"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "_migration", "contact.php")

FORM = """<div class="input-wrapper">
[text* contact-name id:name class:input class:t-m-md size:48 maxlength:400 placeholder "Enter your name"]
[text* contact-company id:company class:input class:t-m-md size:48 maxlength:400 placeholder "Company"]
[email* contact-email id:email class:input class:t-m-md size:48 maxlength:400 placeholder "Email"]
[tel* contact-mobile id:mobile class:input class:t-m-md size:48 maxlength:400 placeholder "Mobile"]
</div>
<div class="input-wrapper">
[textarea* contact-message id:message class:input class:text-area class:t-m-md 52x10 maxlength:2000 placeholder "Your Message"]
</div>
[submit class:btn class:form "Submit"]
[cf7-simple-turnstile]"""

MAIL_BODY = """Name: [contact-name]
Company: [contact-company]
Email: [contact-email]
Mobile: [contact-mobile]

[contact-message]

--
Sent from the contact form on [_site_title] ([_site_url])"""

PHP = """<?php
/**
 * The Contact Form 7 form the contact page points at.
 *
 * Generated by _tools/seed_contact.py -- run on every install once CF7 is active:
 *
 *   docker compose --profile tools run --rm cli wp eval-file /migration/contact.php
 *
 * Rerunning it puts the form back exactly as generated, which is how an experiment in
 * Contact → Contact Forms is undone.
 */

if ( ! class_exists( 'WPCF7_ContactForm' ) ) {
\tWP_CLI::error( 'Contact Form 7 is not active.' );
}

$form = wpcf7_get_contact_form_by_title( 'Contact' );
if ( ! $form ) {
\t// CF7 makes a sample form on activation. Reuse it rather than leave it beside ours.
\t$form = wpcf7_get_contact_form_by_title( 'Contact form 1' );
}
if ( ! $form ) {
\t$form = WPCF7_ContactForm::get_template( array( 'title' => 'Contact' ) );
}

$form->set_title( 'Contact' );
$form->set_properties(
\tarray(
\t\t'form'                => <<<'TPL'
%(form)s
TPL
\t\t,
\t\t'mail'                => array(
\t\t\t'subject'            => '[_site_title]: request from [contact-name]',
\t\t\t'sender'             => '[_site_title] <[_site_admin_email]>',
\t\t\t'recipient'          => '[_osous_email]',
\t\t\t'body'               => <<<'BODY'
%(body)s
BODY
\t\t\t,
\t\t\t'additional_headers' => 'Reply-To: [contact-email]',
\t\t\t'attachments'        => '',
\t\t\t'use_html'           => false,
\t\t\t'exclude_blank'      => false,
\t\t),
\t\t'additional_settings' => '',
\t)
);
$id = $form->save();

/*
 * Cloudflare's published test keys: the widget renders and always passes. Only where the
 * key is empty -- a real key, once entered, stays.
 */
if ( '' === (string) get_option( 'cfturnstile_key', '' ) ) {
\tupdate_option( 'cfturnstile_key', '1x00000000000000000000AA' );
\tupdate_option( 'cfturnstile_secret', '1x0000000000000000000000000000000AA' );
\tupdate_option( 'cfturnstile_tested', 'yes' );
\tdelete_option( 'cfturnstile_do_activation_redirect' );
}

WP_CLI::success( sprintf( 'form "Contact" is post %%d (hash %%s)', $id, substr( (string) get_post_meta( $id, '_hash', true ), 0, 7 ) ) );
"""


def main():
    text = PHP % {"form": FORM, "body": MAIL_BODY}
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
