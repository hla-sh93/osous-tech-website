# -*- coding: utf-8 -*-
"""
The kinds of page: is every one whole, and is every page the kind it should be?

    python _tools/verify_templates.py

A kind of page is a template, a starter and a title, written down in three places that
have to agree: `_tools/kinds.py`, which the migration reads; `functions/templates.php`,
which WordPress and the editor read; and the files themselves -- `templates/page-<kind>.php`
with its `Template Name`, `patterns/starters/<kind>.php` with its slug. This asks
WordPress what it has and holds it against the other two:

  - the table in the theme is the table in kinds.py, in the same order
  - WordPress offers exactly those templates for a page, by those names, and the
    "Create custom template" panel is off (block templates are not supported)
  - every kind's starter is registered, kept out of the inserter, for pages, and made
    only of blocks the theme registers; the page it was lifted from is of that kind
  - every page of the site is on its kind's template, and names its original
  - every file under theme/pages/ is the page it is named for: the same blocks, with the
    same attributes, as the page WordPress holds

Nothing else looks at any of this. The pages render the same on every template, so a
page on the wrong one -- or on none -- passes every other check here.

**Passing looks like:** `0 problems`
"""
import io
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from kinds import KINDS, page_kinds, starter_of, template_of  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, "theme")
PROBE = os.path.join(ROOT, "_migration", "verify_templates.php")

PHP = r"""<?php
/**
 * What WordPress holds about the kinds of page. Generated by _tools/verify_templates.py.
 */

/**
 * Parsed blocks, reduced to what makes two pieces of content the same content: each
 * block's name and attributes, a core block's own markup with its white space
 * collapsed, and its inner blocks. The white space between blocks -- the indentation a
 * file is written with -- is not content.
 */
function osous_verify_shape( $blocks ) {
	$shape = array();
	foreach ( $blocks as $block ) {
		if ( null === $block['blockName'] ) {
			continue;
		}
		$html = '';
		if ( 0 === strpos( $block['blockName'], 'core/' ) ) {
			$html = trim( preg_replace( '/\s+/', ' ', implode( '', array_filter( $block['innerContent'], 'is_string' ) ) ) );
		}
		$shape[] = array( $block['blockName'], $block['attrs'], $html, osous_verify_shape( $block['innerBlocks'] ) );
	}
	return $shape;
}

function osous_verify_names( $blocks, &$names ) {
	foreach ( $blocks as $block ) {
		if ( null !== $block['blockName'] ) {
			$names[] = $block['blockName'];
			osous_verify_names( $block['innerBlocks'], $names );
		}
	}
}

$out = array(
	'kinds'     => osous_page_kinds(),
	'order'     => array_keys( osous_page_kinds() ),
	'supports'  => current_theme_supports( 'block-templates' ),
	'templates' => wp_get_theme()->get_page_templates( null, 'page' ),
	'starters'  => array(),
	'pages'     => array(),
);

$patterns = WP_Block_Patterns_Registry::get_instance();
$types    = WP_Block_Type_Registry::get_instance();
foreach ( osous_page_kinds() as $key => $kind ) {
	$pattern = $patterns->get_registered( $kind['starter'] );
	if ( ! $pattern ) {
		$out['starters'][ $key ] = null;
		continue;
	}
	$names = array();
	osous_verify_names( parse_blocks( $pattern['content'] ), $names );
	$unknown = array();
	foreach ( array_unique( $names ) as $name ) {
		if ( ! $types->is_registered( $name ) ) {
			$unknown[] = $name;
		}
	}
	$out['starters'][ $key ] = array(
		'inserter'   => isset( $pattern['inserter'] ) ? (bool) $pattern['inserter'] : true,
		'postTypes'  => isset( $pattern['postTypes'] ) ? $pattern['postTypes'] : array(),
		'categories' => isset( $pattern['categories'] ) ? $pattern['categories'] : array(),
		'blocks'     => count( $names ),
		'unknown'    => $unknown,
	);
}

foreach ( get_posts( array( 'post_type' => 'page', 'post_status' => 'publish', 'numberposts' => -1 ) ) as $page ) {
	$original = (string) get_post_meta( $page->ID, '_osous_original', true );
	$row      = array(
		'template' => (string) get_post_meta( $page->ID, '_wp_page_template', true ),
		'original' => $original,
		'file'     => false,
		'same'     => null,
	);
	if ( '' !== $original ) {
		$file = get_theme_file_path( 'pages/' . sanitize_key( $original ) . '.php' );
		if ( file_exists( $file ) ) {
			ob_start();
			include $file;
			$body        = ob_get_clean();
			$row['file'] = true;
			$row['same'] = osous_verify_shape( parse_blocks( $body ) ) === osous_verify_shape( parse_blocks( $page->post_content ) );
		}
	}
	$out['pages'][ $page->post_name ] = $row;
}

echo 'OSOUS-JSON' . wp_json_encode( $out );
"""


def wordpress():
    """What WordPress has, through WP-CLI."""
    if not os.path.isdir(os.path.dirname(PROBE)):
        os.makedirs(os.path.dirname(PROBE))
    io.open(PROBE, "w", encoding="utf-8", newline="\n").write(PHP)
    command = ["docker", "compose", "--profile", "tools", "run", "--rm", "-T", "cli", "wp",
               "eval-file", "/migration/verify_templates.php"]
    env = dict(os.environ, MSYS_NO_PATHCONV="1")
    done = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, env=env, encoding="utf-8")
    start = done.stdout.find("OSOUS-JSON")
    if start < 0:
        raise SystemExit("WP-CLI returned nothing -- is the stack up?\n" + done.stdout[-600:] + done.stderr[-600:])
    return json.loads(done.stdout[start + len("OSOUS-JSON"):])


def header(path, field):
    """A `Field: value` line of a file's opening comment, or None."""
    text = io.open(path, encoding="utf-8").read(4000)
    found = re.search(r"^\s*\*\s*%s:\s*(.+?)\s*$" % re.escape(field), text, re.M)
    return found.group(1) if found else None


def main():
    wp = wordpress()
    kinds = page_kinds()
    problems = []

    # ---------------------------------------------------------------- the three tables
    if wp["order"] != list(KINDS):
        problems.append("the theme lists the kinds as %s, kinds.py as %s" % (wp["order"], list(KINDS)))
    for key, kind in KINDS.items():
        theirs = wp["kinds"].get(key)
        if not theirs:
            problems.append("functions/templates.php has no kind %r" % key)
            continue
        for field, mine in (("title", kind["title"]), ("description", kind["description"]),
                            ("template", template_of(key)), ("starter", starter_of(key))):
            if theirs[field] != mine:
                problems.append("%s: %s is %r in the theme and %r in kinds.py" % (key, field, theirs[field], mine))

        path = os.path.join(THEME, template_of(key).replace("/", os.sep))
        if not os.path.exists(path):
            problems.append("%s: no file %s" % (key, template_of(key)))
        elif header(path, "Template Name") != kind["title"]:
            problems.append("%s: %s is named %r, the kind is %r"
                            % (key, template_of(key), header(path, "Template Name"), kind["title"]))

    # ---------------------------------------------------------------- what the editor offers
    offered = wp["templates"] or {}
    expected = dict((template_of(key), kind["title"]) for key, kind in KINDS.items())
    if offered != expected:
        problems.append("WordPress offers %s as page templates; the kinds are %s"
                        % (sorted(offered.items()), sorted(expected.items())))
    if wp["supports"]:
        problems.append("block templates are supported: the Template panel offers "
                        "\"Create custom template\" instead of the kinds")

    # ---------------------------------------------------------------- the starters
    for key in KINDS:
        starter = wp["starters"].get(key)
        path = os.path.join(THEME, "patterns", "starters", key + ".php")
        if not starter:
            problems.append("%s: its starter %s is not registered" % (key, starter_of(key)))
            continue
        if starter["inserter"]:
            problems.append("%s: its starter is offered in the inserter" % key)
        if starter["postTypes"] != ["page"]:
            problems.append("%s: its starter is for %r, not for pages" % (key, starter["postTypes"]))
        if starter["unknown"]:
            problems.append("%s: its starter holds blocks nobody registers: %s" % (key, ", ".join(starter["unknown"])))
        if not starter["blocks"]:
            problems.append("%s: its starter is empty" % key)
        source = re.search(r"from ([a-z0-9-]+), all \d+ sections", io.open(path, encoding="utf-8").read(2000))
        if not source:
            problems.append("%s: its starter does not say which page it was lifted from" % key)
        elif kinds.get(source.group(1)) != key:
            problems.append("%s: its starter was lifted from %s, which is a %s page"
                            % (key, source.group(1), kinds.get(source.group(1))))

    # ---------------------------------------------------------------- the pages
    on_template = same = 0
    for slug, kind in sorted(kinds.items()):
        page = wp["pages"].get(slug)
        if not page:
            problems.append("%s: no such page in WordPress" % slug)
            continue
        if page["template"] != template_of(kind):
            problems.append("%s: on the template %r, its kind's is %r" % (slug, page["template"], template_of(kind)))
        else:
            on_template += 1
        if kind is None:
            if page["original"]:
                problems.append("%s: names an original, and has no sections of its own" % slug)
            continue
        if page["original"] != slug:
            problems.append("%s: names %r as its original" % (slug, page["original"]))
        elif not page["file"]:
            problems.append("%s: theme/pages/%s.php does not exist" % (slug, slug))
        elif not page["same"]:
            problems.append("%s: theme/pages/%s.php is not the page WordPress holds" % (slug, slug))
        else:
            same += 1

    # ---------------------------------------------------------------- the files
    folder = os.path.join(THEME, "pages")
    files = sorted(name[:-4] for name in os.listdir(folder) if name.endswith(".php")) if os.path.isdir(folder) else []
    wanted = sorted(slug for slug, kind in kinds.items() if kind is not None)
    for slug in sorted(set(files) - set(wanted)):
        problems.append("theme/pages/%s.php is no page of the site" % slug)
    for slug in sorted(set(wanted) - set(files)):
        problems.append("theme/pages/%s.php is missing" % slug)
    for slug in sorted(set(files) & set(wanted)):
        path = os.path.join(folder, slug + ".php")
        if header(path, "Page") != slug:
            problems.append("theme/pages/%s.php says it is the page %r" % (slug, header(path, "Page")))
        if header(path, "Template") != template_of(kinds[slug]):
            problems.append("theme/pages/%s.php names the template %r, its kind's is %r"
                            % (slug, header(path, "Template"), template_of(kinds[slug])))

    print("%d kinds, %d templates offered, %d starters registered"
          % (len(wp["kinds"]), len(offered), sum(1 for s in wp["starters"].values() if s)))
    print("%d of %d pages on their kind's template; %d of %d page files the same as the pages"
          % (on_template, len(kinds), same, len(wanted)))
    for problem in problems:
        print("  !! " + problem)
    print("%d problems" % len(problems))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
