# -*- coding: utf-8 -*-
"""
Generate a PHP seeding script for the local WordPress.

Reads the static pages for their slugs and titles, and index.html's navbar for the
menu tree, then emits PHP that `wp eval-file` runs in one shot. Local only — on
production the pages and menus already exist.

Every page is also given its kind -- the page template its sections belong to
(_tools/kinds.py) -- and the name of its original under theme/pages/, which is what the
editor's "Restore the original sections" looks up whatever the page's slug has become.

And what its <head> says: the reference page's document title and description go into
Rank Math's own fields on the page (`rank_math_title`, `rank_math_description`), which is
where they are edited from then on. The theme prints neither; without the plugin the
fields are simply not read.
"""
import io, json, os, glob, re, sys
from lxml import html as LH

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from kinds import page_kinds, template_of  # noqa: E402
from refpage import page_seo, page_title  # noqa: E402

ROOT = "D:/abbas/osous-tech-website"


def slug_of(href):
    href = (href or "").strip()
    if not href or href.startswith(("#", "http", "mailto:", "tel:")):
        return None
    return href[:-5] if href.endswith(".html") else None


# ---------------------------------------------------------------- pages
kinds = page_kinds()
pages = {}
for p in sorted(glob.glob(os.path.join(ROOT, "*.html"))):
    slug = os.path.basename(p)[:-5]
    pages[slug] = {
        "title": page_title(slug),
        "template": template_of(kinds[slug]),
        # The blog is the posts index and has no sections of its own, so no original.
        "original": slug if kinds[slug] else "",
        # What the reference page's <head> tells a search engine, for the SEO plugin's fields.
        "seo": page_seo(slug),
    }

# ---------------------------------------------------------------- primary menu
doc = LH.parse(os.path.join(ROOT, "index.html")).getroot()
header = doc.xpath("//header")[0]
primary = []

for node in header.xpath('.//nav[contains(@class,"navbar-menu")]/div'):
    cls = node.get("class") or ""
    if "navbar-mobile-buttons" in cls:
        continue

    if "dd-menu-item" in cls:
        label = node.xpath('.//span[@class="nav-link"]/text()')
        entry = {
            "title": (label[0].strip() if label else "?"),
            "url": None,
            "classes": "hide-on-desktop" if "hide-on-desktop" in cls else "",
            "children": [],
        }
        for col in node.xpath('.//div[@class="menu"]/div[@class="dd-menu-list"]'):
            title = col.xpath('.//a[contains(@class,"menu-title") and contains(@class,"hide-on-tablet")]')
            leaves = col.xpath('.//div[@class="menu-list"]/a')
            if title:
                group = {
                    "title": " ".join(title[0].text_content().split()),
                    "url": slug_of(title[0].get("href")),
                    "classes": "",
                    "children": [
                        {"title": " ".join(a.text_content().split()),
                         "url": slug_of(a.get("href")), "classes": "", "children": []}
                        for a in leaves
                    ],
                }
                entry["children"].append(group)
            else:
                # a bare column: its links belong directly under the dropdown
                for a in leaves:
                    entry["children"].append(
                        {"title": " ".join(a.text_content().split()),
                         "url": slug_of(a.get("href")), "classes": "", "children": []}
                    )
        primary.append(entry)
    elif "menu-item" in cls:
        a = node.xpath(".//a")[0]
        primary.append({
            "title": " ".join(a.text_content().split()),
            "url": slug_of(a.get("href")),
            "classes": "hide-on-desktop" if "hide-on-desktop" in cls else "",
            "children": [],
        })

# ---------------------------------------------------------------- footer menus
footer = doc.xpath("//footer")[0]
discover = [
    {"title": " ".join(a.text_content().split()), "url": slug_of(a.get("href")), "classes": "", "children": []}
    for a in footer.xpath('.//div[contains(@class,"footer-col-discover")]//a')
]
legal = [
    {"title": " ".join(a.text_content().split()), "url": slug_of(a.get("href")), "classes": "", "children": []}
    for a in footer.xpath('.//div[contains(@class,"footer-legal")]//a')
]

data = {
    "pages": pages,
    "menus": {
        "primary": {"name": "Primary", "items": primary},
        "footer-discover": {"name": "Footer Discover", "items": discover},
        "footer-legal": {"name": "Footer Legal", "items": legal},
    },
}

payload = json.dumps(data, ensure_ascii=False)
php = """<?php
/**
 * Seeds the local WordPress with the pages and menus taken from the static site.
 * Generated by _tools/seed.py -- local development only.
 */

$data = json_decode( <<<'JSON'
%s
JSON
, true );

// ------------------------------------------------------------------ pages
$ids = array();
foreach ( $data['pages'] as $slug => $page ) {
\t$title    = $page['title'];
\t$existing = get_page_by_path( $slug, OBJECT, 'page' );
\tif ( $existing ) {
\t\t/*
\t\t * WordPress ships its own Privacy Policy page, as a draft, on a slug we want.
\t\t * Adopt it -- and empty it: it carries five kilobytes of boilerplate that the
\t\t * theme never renders, which would be invisible cruft until Phase 3 opens the
\t\t * page in the editor and shows it to whoever is editing.
\t\t */
\t\tif ( 'publish' !== $existing->post_status || $existing->post_title !== $title
\t\t\t|| '' !== trim( $existing->post_content ) ) {
\t\t\twp_update_post( array(
\t\t\t\t'ID'           => $existing->ID,
\t\t\t\t'post_status'  => 'publish',
\t\t\t\t'post_title'   => $title,
\t\t\t\t'post_content' => '',
\t\t\t) );
\t\t}
\t\t$ids[ $slug ] = $existing->ID;
\t\tcontinue;
\t}
\t$ids[ $slug ] = wp_insert_post( array(
\t\t'post_type'    => 'page',
\t\t'post_status'  => 'publish',
\t\t'post_name'    => $slug,
\t\t'post_title'   => $title,
\t\t'post_content' => '',
\t) );
}
/*
 * Each page's kind and its original. The template is WordPress's own page-template meta,
 * so the editor's Template panel shows it and a page keeps it whatever its slug becomes;
 * `_osous_original` names the file under theme/pages/ the page was built from.
 */
foreach ( $data['pages'] as $slug => $page ) {
\tupdate_post_meta( $ids[ $slug ], '_wp_page_template', $page['template'] );
\tif ( '' !== $page['original'] ) {
\t\tupdate_post_meta( $ids[ $slug ], '_osous_original', $page['original'] );
\t} else {
\t\tdelete_post_meta( $ids[ $slug ], '_osous_original' );
\t}
\t// Slashed: update_post_meta() unslashes, and a title may hold a quote.
\tforeach ( array( 'title' => 'rank_math_title', 'description' => 'rank_math_description' ) as $field => $meta_key ) {
\t\tif ( '' !== $page['seo'][ $field ] ) {
\t\t\tupdate_post_meta( $ids[ $slug ], $meta_key, wp_slash( $page['seo'][ $field ] ) );
\t\t}
\t}
}

// WordPress's own Sample Page is not one of ours and has no business being published.
$sample = get_page_by_path( 'sample-page', OBJECT, 'page' );
if ( $sample ) {
\twp_delete_post( $sample->ID, true );
}

WP_CLI::log( sprintf( 'pages: %%d', count( $ids ) ) );

if ( isset( $ids['index'] ) ) {
\tupdate_option( 'show_on_front', 'page' );
\tupdate_option( 'page_on_front', $ids['index'] );
}
/*
 * `page_for_posts` is not set here. The posts seed (posts.php) sets it once there are
 * posts for /blog/ to show; until then it is a page like any other.
 */
delete_option( 'page_for_posts' );

// ------------------------------------------------------------------ menus
function osous_seed_items( $menu_id, $items, $parent, $ids ) {
\t$n = 0;
\tforeach ( $items as $i => $item ) {
\t\t$args = array(
\t\t\t'menu-item-title'     => $item['title'],
\t\t\t'menu-item-status'    => 'publish',
\t\t\t'menu-item-parent-id' => $parent,
\t\t\t'menu-item-position'  => $i + 1,
\t\t\t'menu-item-classes'   => $item['classes'],
\t\t);
\t\tif ( $item['url'] && isset( $ids[ $item['url'] ] ) ) {
\t\t\t$args['menu-item-type']      = 'post_type';
\t\t\t$args['menu-item-object']    = 'page';
\t\t\t$args['menu-item-object-id'] = $ids[ $item['url'] ];
\t\t} else {
\t\t\t$args['menu-item-type'] = 'custom';
\t\t\t$args['menu-item-url']  = '#';
\t\t}
\t\t$id = wp_update_nav_menu_item( $menu_id, 0, $args );
\t\t$n++;
\t\tif ( ! empty( $item['children'] ) ) {
\t\t\t$n += osous_seed_items( $menu_id, $item['children'], $id, $ids );
\t\t}
\t}
\treturn $n;
}

$locations = array();
foreach ( $data['menus'] as $location => $menu ) {
\t$existing = wp_get_nav_menu_object( $menu['name'] );
\tif ( $existing ) {
\t\twp_delete_nav_menu( $existing->term_id );
\t}
\t$menu_id = wp_create_nav_menu( $menu['name'] );
\t$count   = osous_seed_items( $menu_id, $menu['items'], 0, $ids );
\t$locations[ $location ] = $menu_id;
\tWP_CLI::log( sprintf( 'menu %%-16s %%d items', $menu['name'], $count ) );
}
set_theme_mod( 'nav_menu_locations', $locations );

WP_CLI::success( 'seeded' );
""" % payload

out = os.path.join(ROOT, "_migration", "seed.php")
io.open(out, "w", encoding="utf-8", newline="\n").write(php)
print(f"wrote {out}")
print(f"  pages          {len(pages)}")
print(f"  primary items  {len(primary)} top-level")
for e in primary:
    kids = sum(1 + len(c['children']) for c in e['children'])
    print(f"     {e['title']:<12} {len(e['children'])} children ({kids} total)")
print(f"  discover       {len(discover)}")
print(f"  legal          {len(legal)}")
