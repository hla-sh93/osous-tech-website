# -*- coding: utf-8 -*-
"""
Write one PHP fixture per page from the static HTML.

Phase 2 keeps section data in the theme so the renderer can be proven correct before an
editor exists. Phase 3 moves the same arrays into the database as block attributes; the
shape does not change, which is the point of generating rather than hand-writing them.

    python _tools/gen_fixtures.py
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from extract import ROOT, extract_all  # noqa: E402

OUT = os.path.join(ROOT, "theme", "fixtures")

# Printed in this order so a fixture reads as shape first, then content.
KEY_ORDER = ["t", "g", "n", "c", "id", "role", "aria-hidden", "aria-label", "aria-current",
             "href", "target", "rel", "method", "action", "type", "name", "size", "cols",
             "rows", "maxlength", "placeholder", "value", "required", "src", "srcset",
             "sizes", "alt", "width", "height", "fetchpriority", "data-paged", "data-query",
             "fs-list-element", "fs-list-load", "udy-collection", "x", "k"]
RANK = {k: i for i, k in enumerate(KEY_ORDER)}


def php_string(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def php_value(value, indent):
    pad = "\t" * indent
    if value is True:
        return "true"
    if isinstance(value, str):
        return php_string(value)
    if isinstance(value, list):
        if not value:
            return "array()"
        rows = ",\n".join(pad + "\t" + php_value(v, indent + 1) for v in value)
        return "array(\n" + rows + ",\n" + pad + ")"
    if isinstance(value, dict):
        keys = sorted(value, key=lambda k: RANK.get(k, len(RANK)))
        rows = ",\n".join(
            "%s\t%s => %s" % (pad, php_string(k), php_value(value[k], indent + 1))
            for k in keys
        )
        return "array(\n" + rows + ",\n" + pad + ")"
    raise TypeError(repr(value))


HEADER = """<?php
/**
 * Section data for /%s/.
 *
 * Generated by _tools/gen_fixtures.py from %s.html -- do not edit by hand.
 * Rendered by inc/sections.php; replaced by block content in Phase 3.
 *
 * @package Osous
 */

if ( ! defined( 'ABSPATH' ) ) {
\texit;
}

return %s;
"""


def main():
    pages = extract_all()
    if not os.path.isdir(OUT):
        os.makedirs(OUT)

    written, total = 0, 0
    for slug, sections in sorted(pages.items()):
        body = php_value(sections, 0)
        text = HEADER % (slug, slug, body)
        path = os.path.join(OUT, slug + ".php")
        io.open(path, "w", encoding="utf-8", newline="\n").write(text)
        written += 1
        total += len(sections)

    print("%d fixtures, %d sections, %.0f KB" % (
        written, total,
        sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) / 1024.0))


if __name__ == "__main__":
    main()
