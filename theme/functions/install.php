<?php
/**
 * Install the site's pages: the theme puts its own pages into WordPress.
 *
 * Appearance → Site pages, or `wp osous install-pages`. Every page's original is in the
 * theme (pages/<key>.php), and install/site.json says the rest: each page's title, its
 * template, what it tells a search engine, the three menus and the contact form. This
 * puts all of it into whatever WordPress the theme is on.
 *
 * Two kinds of site have to come out the same. An empty WordPress, where every page is
 * made. And the live one, which already holds every page at its address -- published,
 * empty, on the default template, because the old theme drew them -- along with the real
 * posts. An import would add each page a second time at `<slug>-2`; this fills each page
 * where it is, so it keeps its id, its address, its history, its comments and whatever is
 * in its search fields already.
 *
 * What it never does: touch a post, delete anything, or overwrite a page that has content
 * of its own unless asked to -- and then the content it had is kept as a revision first.
 * Run twice, the second run changes nothing.
 *
 * Which page is which. A page is found, in this order, as:
 *
 *   1. the page installed from that original before (`_osous_original`), whatever its
 *      address has become since;
 *   2. for the home page and the blog, the page the site's Reading settings name;
 *   3. the published page at that address, or that had it (functions/links.php);
 *   4. a page with that slug that is not published -- WordPress's own draft Privacy
 *      Policy, on a fresh install.
 *
 * Only this file finds a page by its address, and only to install it: everywhere else a
 * page is known by its id.
 *
 * @package Osous
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * What install/site.json says: the pages, the menus and the contact form.
 *
 * Generated by _tools/seed.py from the reference pages.
 *
 * @return array{pages:array<string,array>,menus:array<string,array>,contact_form:array}
 */
function osous_install_data() {
	static $data = null;

	if ( null === $data ) {
		$json = wp_json_file_decode( get_theme_file_path( 'install/site.json' ), array( 'associative' => true ) );
		$data = wp_parse_args(
			is_array( $json ) ? $json : array(),
			array(
				'pages'        => array(),
				'menus'        => array(),
				'contact_form' => array(),
			)
		);
	}

	return $data;
}

/**
 * Every page WordPress holds that is not in the bin, read once.
 *
 * @return array{originals:array<string,int>,unpublished:array<string,int>}
 */
function osous_install_state() {
	// A hundred at a time, for a site with more pages than that.
	$ids   = array();
	$paged = 1;
	do {
		$query = new WP_Query(
			array(
				'post_type'              => 'page',
				'post_status'            => array( 'publish', 'draft', 'pending', 'private', 'future' ),
				'fields'                 => 'ids',
				'posts_per_page'         => 100,
				'paged'                  => $paged,
				'orderby'                => 'ID',
				'order'                  => 'ASC',
				'update_post_term_cache' => false,
			)
		);
		$ids   = array_merge( $ids, $query->posts );
		++$paged;
	} while ( $paged <= $query->max_num_pages );

	$state = array(
		'originals'   => array(),
		'unpublished' => array(),
	);
	foreach ( $ids as $id ) {
		$id       = (int) $id;
		$original = (string) get_post_meta( $id, '_osous_original', true );
		if ( '' !== $original && ! isset( $state['originals'][ $original ] ) ) {
			$state['originals'][ $original ] = $id;
		}
		$post = get_post( $id );
		if ( 'publish' !== $post->post_status && 0 === (int) $post->post_parent && '' !== $post->post_name
			&& ! isset( $state['unpublished'][ $post->post_name ] ) ) {
			$state['unpublished'][ $post->post_name ] = $id;
		}
	}

	return $state;
}

/**
 * The page that is this one on this site, and how it was known.
 *
 * @param string $key   The page's key: its slug on the reference site.
 * @param array  $page  Its entry in site.json.
 * @param array  $state What osous_install_state() read.
 * @return array{0:int,1:string} The page's id, 0 when there is none, and how it was found.
 */
function osous_install_find( $key, $page, $state ) {
	if ( '' !== $page['original'] && isset( $state['originals'][ $page['original'] ] ) ) {
		return array( $state['originals'][ $page['original'] ], 'original' );
	}

	$settings = array(
		'index' => 'page_on_front',
		'blog'  => 'page_for_posts',
	);
	if ( isset( $settings[ $key ] ) && ( 'blog' === $key || 'page' === get_option( 'show_on_front' ) ) ) {
		$id = (int) get_option( $settings[ $key ] );
		if ( $id && 'page' === get_post_type( $id ) && 'publish' === get_post_status( $id ) ) {
			return array( $id, 'setting' );
		}
	}

	$id = osous_page_id( $key );
	if ( $id ) {
		return array( $id, 'address' );
	}

	if ( isset( $state['unpublished'][ $key ] ) ) {
		return array( $state['unpublished'][ $key ], 'unpublished' );
	}

	return array( 0, '' );
}

/**
 * What installing would do to each page.
 *
 * The actions: `create` (no such page), `fill` (the page is empty), `publish` (it is not
 * published, and is empty or WordPress's own draft), `current` (it holds its sections
 * already), `kept` (it has content of its own, left alone), `replace` (it has, and the
 * person asked for it to be replaced).
 *
 * @param bool $replace Replace the content of pages that have some of their own.
 * @param bool $compare Read each original to tell `current` from `kept`. The notice that
 *                      only asks "is anything missing?" leaves it off.
 * @return array<int,array<string,mixed>>
 */
function osous_install_plan( $replace = false, $compare = true ) {
	$data  = osous_install_data();
	$state = osous_install_state();
	$rows  = array();

	foreach ( $data['pages'] as $key => $page ) {
		list( $id, $found ) = osous_install_find( $key, $page, $state );

		$row = array(
			'key'      => $key,
			'title'    => $page['title'],
			'template' => $page['template'],
			'original' => $page['original'],
			'id'       => $id,
			'found'    => $found,
		);

		if ( ! $id ) {
			$row['action'] = 'create';
			$rows[]        = $row;
			continue;
		}

		$published = 'publish' === get_post_status( $id );
		$content   = trim( (string) get_post_field( 'post_content', $id ) );
		// WordPress's own draft Privacy Policy is its boilerplate, never anybody's work.
		$boilerplate = ! $published && (int) get_option( 'wp_page_for_privacy_policy' ) === $id;

		if ( '' === $page['original'] ) {
			// The blog: a page whose content is never shown. Only its being there matters.
			$row['action'] = $published ? 'current' : 'publish';
		} elseif ( '' === $content || $boilerplate ) {
			$row['action'] = $published ? 'fill' : 'publish';
		} elseif ( $compare && osous_original_markup( $page['original'], true ) === $content ) {
			$row['action'] = $published ? 'current' : 'publish';
		} else {
			$row['action'] = $replace ? 'replace' : 'kept';
		}

		$rows[] = $row;
	}

	return $rows;
}

/**
 * Install one page as the plan says.
 *
 * @param array $row  Its row of the plan.
 * @param array $page Its entry in site.json.
 * @return int|WP_Error The page's id.
 */
function osous_install_page( $row, $page ) {
	$id     = (int) $row['id'];
	$markup = '' !== $page['original'] ? osous_original_markup( $page['original'], true ) : '';

	if ( 'kept' === $row['action'] ) {
		return $id;
	}

	if ( 'create' === $row['action'] ) {
		// Slashed, because wp_insert_post() unslashes: the blocks' attributes carry \u escapes.
		$id = wp_insert_post(
			wp_slash(
				array(
					'post_type'    => 'page',
					'post_status'  => 'publish',
					'post_name'    => $row['key'],
					'post_title'   => $page['title'],
					'post_content' => $markup,
				)
			),
			true
		);
		if ( is_wp_error( $id ) ) {
			return $id;
		}
	} elseif ( 'current' !== $row['action'] ) {
		$update = array( 'ID' => $id );
		if ( '' !== $page['original'] ) {
			$update['post_content'] = $markup;
		}
		if ( 'publish' === $row['action'] ) {
			$update['post_status'] = 'publish';
		}
		if ( '' === trim( (string) get_post_field( 'post_title', $id ) ) ) {
			$update['post_title'] = $page['title'];
		}
		if ( 'replace' === $row['action'] ) {
			// What it holds now, kept where Revisions will show it.
			wp_save_post_revision( $id );
		}
		$id = wp_update_post( wp_slash( $update ), true );
		if ( is_wp_error( $id ) ) {
			return $id;
		}
	}

	/*
	 * The template is the page's kind. A page that already held its sections keeps the
	 * template it has, which somebody may have chosen since; every other one is given its
	 * kind's.
	 */
	$template = (string) get_post_meta( $id, '_wp_page_template', true );
	if ( 'current' !== $row['action'] || '' === $template || 'default' === $template ) {
		update_post_meta( $id, '_wp_page_template', $page['template'] );
	}
	if ( '' !== $page['original'] ) {
		update_post_meta( $id, '_osous_original', $page['original'] );
	}

	// What it tells a search engine: only where the field is empty, so the site's own stays.
	$fields = array(
		'title'       => 'rank_math_title',
		'description' => 'rank_math_description',
	);
	foreach ( $fields as $field => $meta_key ) {
		if ( ! empty( $page['seo'][ $field ] ) && '' === (string) get_post_meta( $id, $meta_key, true ) ) {
			update_post_meta( $id, $meta_key, wp_slash( $page['seo'][ $field ] ) );
		}
	}

	return (int) $id;
}

/**
 * The front page and the posts page, where they are not set.
 *
 * @param array<string,int> $ids The installed pages, by key.
 * @return string[] What was done, for the report.
 */
function osous_install_reading( $ids ) {
	$notes = array();

	if ( ! empty( $ids['index'] ) ) {
		$front = (int) get_option( 'page_on_front' );
		if ( 'page' !== get_option( 'show_on_front' ) || ! $front || 'publish' !== get_post_status( $front ) ) {
			update_option( 'show_on_front', 'page' );
			update_option( 'page_on_front', $ids['index'] );
			$notes[] = __( 'The home page is now the front page (Settings → Reading).', 'osous' );
		} elseif ( $front !== $ids['index'] ) {
			/* translators: %s: a page's title. */
			$notes[] = sprintf( __( 'The front page is “%s”, which is not the home page. Left as it is: change it under Settings → Reading.', 'osous' ), get_the_title( $front ) );
		}
	}

	if ( ! empty( $ids['blog'] ) ) {
		$posts = (int) get_option( 'page_for_posts' );
		if ( ! $posts || 'publish' !== get_post_status( $posts ) ) {
			update_option( 'page_for_posts', $ids['blog'] );
			$notes[] = __( 'The blog page now shows the posts (Settings → Reading).', 'osous' );
		} elseif ( $posts !== $ids['blog'] ) {
			/* translators: %s: a page's title. */
			$notes[] = sprintf( __( 'The posts are shown on “%s”, not on the blog page. Left as it is: change it under Settings → Reading.', 'osous' ), get_the_title( $posts ) );
		}
	}

	return $notes;
}

/**
 * Lay a menu's items down, children under their parents.
 *
 * @param int               $menu_id The menu.
 * @param array             $items   Its items, from site.json.
 * @param int               $parent_item The item they hang from; 0 for the top.
 * @param array<string,int> $ids     The installed pages, by key.
 * @return int How many items were made.
 */
function osous_install_menu_items( $menu_id, $items, $parent_item, $ids ) {
	$made = 0;
	foreach ( $items as $position => $item ) {
		$args = array(
			'menu-item-title'     => $item['title'],
			'menu-item-status'    => 'publish',
			'menu-item-parent-id' => $parent_item,
			'menu-item-position'  => $position + 1,
			'menu-item-classes'   => $item['classes'],
		);
		if ( $item['url'] && ! empty( $ids[ $item['url'] ] ) ) {
			$args['menu-item-type']      = 'post_type';
			$args['menu-item-object']    = 'page';
			$args['menu-item-object-id'] = $ids[ $item['url'] ];
		} else {
			$args['menu-item-type'] = 'custom';
			$args['menu-item-url']  = '#';
		}
		$item_id = wp_update_nav_menu_item( $menu_id, 0, $args );
		if ( is_wp_error( $item_id ) ) {
			continue;
		}
		++$made;
		if ( ! empty( $item['children'] ) ) {
			$made += osous_install_menu_items( $menu_id, $item['children'], $item_id, $ids );
		}
	}

	return $made;
}

/**
 * The three menus, each in its place.
 *
 * A menu that already has items stays as it is unless `$replace`: the menu in a location,
 * or failing that the menu of that name, is the one that is used. A replaced menu keeps
 * its name and its place; only its items are laid down again.
 *
 * @param array<string,int> $ids     The installed pages, by key.
 * @param bool              $replace Lay the items down again in a menu that has some.
 * @return string[] What was done, for the report.
 */
function osous_install_menus( $ids, $replace ) {
	$locations = get_nav_menu_locations();
	$notes     = array();

	foreach ( osous_install_data()['menus'] as $location => $menu ) {
		$menu_id = empty( $locations[ $location ] ) ? 0 : (int) $locations[ $location ];
		if ( $menu_id && ! wp_get_nav_menu_object( $menu_id ) ) {
			$menu_id = 0;
		}
		if ( ! $menu_id ) {
			$object  = wp_get_nav_menu_object( $menu['name'] );
			$menu_id = $object ? (int) $object->term_id : 0;
		}

		$items = $menu_id ? wp_get_nav_menu_items( $menu_id, array( 'post_status' => 'any' ) ) : array();
		$name  = $menu_id ? wp_get_nav_menu_object( $menu_id )->name : $menu['name'];

		if ( $items && ! $replace ) {
			/* translators: 1: a menu's name, 2: how many items it has. */
			$notes[] = sprintf( __( 'The menu “%1$s” has %2$d items already. Left as it is.', 'osous' ), $name, count( $items ) );
		} else {
			if ( ! $menu_id ) {
				$menu_id = wp_create_nav_menu( $menu['name'] );
				if ( is_wp_error( $menu_id ) ) {
					$notes[] = $menu_id->get_error_message();
					continue;
				}
			}
			foreach ( (array) $items as $item ) {
				wp_delete_post( $item->ID, true );
			}
			$made = osous_install_menu_items( $menu_id, $menu['items'], 0, $ids );
			/* translators: 1: a menu's name, 2: how many items were laid down. */
			$notes[] = sprintf( __( 'The menu “%1$s”: %2$d items laid down.', 'osous' ), $name, $made );
		}

		$locations[ $location ] = (int) $menu_id;
	}
	set_theme_mod( 'nav_menu_locations', $locations );

	return $notes;
}

/**
 * The contact form the contact page names, where there is none of that name.
 *
 * @return string What was done, for the report.
 */
function osous_install_contact_form() {
	$form = osous_install_data()['contact_form'];
	if ( empty( $form['title'] ) ) {
		return '';
	}
	if ( ! class_exists( 'WPCF7_ContactForm' ) || ! function_exists( 'wpcf7_get_contact_form_by_title' ) ) {
		return __( 'Contact Form 7 is not active, so the contact page has no form yet. Activate it and install again.', 'osous' );
	}
	if ( wpcf7_get_contact_form_by_title( $form['title'] ) ) {
		/* translators: %s: the form's title. */
		return sprintf( __( 'The contact form “%s” is there already. Left as it is.', 'osous' ), $form['title'] );
	}

	$new = WPCF7_ContactForm::get_template( array( 'title' => $form['title'] ) );
	$new->set_properties(
		array(
			'form' => $form['form'],
			'mail' => $form['mail'],
		)
	);
	$new->save();

	/* translators: %s: the form's title. */
	return sprintf( __( 'Made the contact form “%s” (Contact → Contact Forms).', 'osous' ), $form['title'] );
}

/**
 * Install everything, or as much as fits in the time given.
 *
 * Saving a page is quick, and what other plugins do on every save is not: on this site
 * Rank Math's link counter and its indexing notice take about 0.6s a page, and a cache
 * plugin purging the page's cache adds to that. Fifty-odd pages in one request is more
 * than many hosts allow one request to take. So the button installs in rounds of
 * `$budget` seconds: a page installed is a page the next round finds already holding its
 * sections, and the next round carries on from there. The menus, the front page and the
 * form come last, in the round that finishes the pages.
 *
 * @param array{replace_content?:bool,replace_menus?:bool,budget?:int} $args What may be
 *        replaced, and how many seconds this round may take; 0 for no limit.
 * @return array{pages:array<int,array>,notes:string[],finished:bool}
 */
function osous_install_run( $args = array() ) {
	$args    = wp_parse_args(
		$args,
		array(
			'replace_content' => false,
			'replace_menus'   => false,
			'budget'          => 0,
		)
	);
	$started = microtime( true );
	$data    = osous_install_data();
	$plan    = osous_install_plan( (bool) $args['replace_content'] );
	$ids     = array();
	$waiting = false;

	foreach ( $plan as $i => $row ) {
		$work = ! in_array( $row['action'], array( 'current', 'kept' ), true );
		if ( $work && $args['budget'] && microtime( true ) - $started > $args['budget'] ) {
			$plan[ $i ]['action'] = 'waiting';
			$waiting              = true;
			continue;
		}
		$id = osous_install_page( $row, $data['pages'][ $row['key'] ] );
		if ( is_wp_error( $id ) ) {
			$plan[ $i ]['action'] = 'failed';
			$plan[ $i ]['error']  = $id->get_error_message();
			continue;
		}
		$plan[ $i ]['id']   = $id;
		$ids[ $row['key'] ] = $id;
	}

	// The pages just made have addresses the links can resolve to.
	osous_page_index( true );

	if ( $waiting ) {
		return array(
			'pages'    => $plan,
			'notes'    => array(),
			'finished' => false,
		);
	}

	$notes = array_merge(
		osous_install_reading( $ids ),
		osous_install_menus( $ids, (bool) $args['replace_menus'] ),
		array( osous_install_contact_form() )
	);

	return array(
		'pages'    => $plan,
		'notes'    => array_values( array_filter( $notes ) ),
		'finished' => true,
	);
}

/**
 * One round's report folded into the rounds before it.
 *
 * A page installed in an earlier round reads as already holding its sections in the next;
 * what the report says about it is what was done to it, so the first thing done stands.
 *
 * @param array|false $earlier The rounds so far, or false for the first.
 * @param array       $round   This round.
 * @return array The report so far.
 */
function osous_install_merge( $earlier, $round ) {
	if ( ! $earlier ) {
		return $round;
	}
	$done = array();
	foreach ( $earlier['pages'] as $row ) {
		$done[ $row['key'] ] = $row;
	}
	foreach ( $round['pages'] as $i => $row ) {
		$before = isset( $done[ $row['key'] ] ) ? $done[ $row['key'] ] : null;
		if ( $before && ! in_array( $before['action'], array( 'current', 'waiting' ), true ) ) {
			$round['pages'][ $i ] = $before;
		}
	}

	return $round;
}

/**
 * The words for each action, before and after.
 *
 * @param bool $done After the run.
 * @return array<string,string>
 */
function osous_install_labels( $done ) {
	if ( $done ) {
		return array(
			'create'  => __( 'Made', 'osous' ),
			'fill'    => __( 'Filled', 'osous' ),
			'publish' => __( 'Filled and published', 'osous' ),
			'current' => __( 'Already held its sections', 'osous' ),
			'kept'    => __( 'Has content of its own: left as it is', 'osous' ),
			'replace' => __( 'Replaced: what it held is kept as a revision', 'osous' ),
			'failed'  => __( 'Failed', 'osous' ),
			'waiting' => __( 'Waiting for the next round', 'osous' ),
		);
	}

	return array(
		'create'  => __( 'Will be made', 'osous' ),
		'fill'    => __( 'Empty: will be filled', 'osous' ),
		'publish' => __( 'Not published: will be filled and published', 'osous' ),
		'current' => __( 'Holds its sections already', 'osous' ),
		'kept'    => __( 'Has content of its own: will be left as it is', 'osous' ),
		'replace' => __( 'Has content of its own: will be replaced, and what it holds kept as a revision', 'osous' ),
	);
}

/**
 * How many pages each action covers.
 *
 * @param array $plan The plan, or the pages of a report.
 * @return array<string,int>
 */
function osous_install_counts( $plan ) {
	$counts = array();
	foreach ( $plan as $row ) {
		$counts[ $row['action'] ] = isset( $counts[ $row['action'] ] ) ? $counts[ $row['action'] ] + 1 : 1;
	}

	return $counts;
}

/**
 * How long one round of the button may take, in seconds: well inside the 30 seconds a
 * host commonly allows a request, with room for the page around it.
 */
const OSOUS_INSTALL_ROUND = 15;

/**
 * Whoever may install: someone who may change the theme's settings and publish anybody's pages.
 *
 * @return bool
 */
function osous_install_allowed() {
	return current_user_can( 'edit_theme_options' ) && current_user_can( 'publish_pages' )
		&& current_user_can( 'edit_others_pages' );
}

/**
 * Appearance → Site pages.
 */
function osous_install_menu() {
	add_theme_page(
		__( 'Install the site’s pages', 'osous' ),
		__( 'Site pages', 'osous' ),
		'edit_theme_options',
		'osous-site-pages',
		'osous_install_screen'
	);
}
add_action( 'admin_menu', 'osous_install_menu' );

/**
 * The screen: what installing would do, page by page, and the button.
 */
function osous_install_screen() {
	if ( ! osous_install_allowed() ) {
		wp_die( esc_html__( 'You are not allowed to install pages.', 'osous' ) );
	}

	$progress = get_transient( 'osous_install_progress_' . get_current_user_id() );
	if ( $progress && ! empty( $_GET['installing'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- only chooses which screen to show; the form it shows carries its own nonce.
		osous_install_progress_screen( $progress );
		return;
	}

	$report_key = 'osous_install_report_' . get_current_user_id();
	$report     = get_transient( $report_key );
	if ( $report ) {
		delete_transient( $report_key );
	}
	$plan   = osous_install_plan();
