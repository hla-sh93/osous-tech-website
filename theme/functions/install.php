	wp_print_inline_script_tag( 'HTMLFormElement.prototype.submit.call( document.getElementById( "osous-install-continue" ) );' );
}

/**
 * The button: install a round, then the next, then keep the report for the screen.
 */
function osous_install_handle() {
	check_admin_referer( 'osous_install_pages' );
	if ( ! osous_install_allowed() ) {
		wp_die( esc_html__( 'You are not allowed to install pages.', 'osous' ) );
	}

	$options  = array(
		'replace_content' => ! empty( $_POST['replace_content'] ),
		'replace_menus'   => ! empty( $_POST['replace_menus'] ),
	);
	$progress = 'osous_install_progress_' . get_current_user_id();
	$so_far   = empty( $_POST['continue'] ) ? false : get_transient( $progress );

	/**
	 * How many seconds one round of the button may take.
	 *
	 * @param int $seconds OSOUS_INSTALL_ROUND.
	 */
	$budget = max( 1, (int) apply_filters( 'osous_install_round', OSOUS_INSTALL_ROUND ) );
	$round  = osous_install_run( $options + array( 'budget' => $budget ) );
	$report = osous_install_merge( $so_far, $round );

	if ( ! $round['finished'] ) {
		set_transient( $progress, $report + array( 'options' => $options ), HOUR_IN_SECONDS );
		wp_safe_redirect( admin_url( 'themes.php?page=osous-site-pages&installing=1' ) );
		exit;
	}

	delete_transient( $progress );
	set_transient( 'osous_install_report_' . get_current_user_id(), $report, 10 * MINUTE_IN_SECONDS );
	wp_safe_redirect( admin_url( 'themes.php?page=osous-site-pages' ) );
	exit;
}
add_action( 'admin_post_osous_install_pages', 'osous_install_handle' );

/**
 * Say so when the site's pages are not installed.
 *
 * The first person to receive this theme uploaded it, activated it, and asked where the
 * other 56 pages were: the step that brings them had been skipped. So the theme says it
 * itself, on the screens somebody looks at first, until there is nothing left to install.
 */
function osous_install_notice() {
	$screen = get_current_screen();
	if ( ! $screen || ! in_array( $screen->id, array( 'dashboard', 'themes', 'edit-page' ), true ) || ! osous_install_allowed() ) {
		return;
	}

	$counts  = osous_install_counts( osous_install_plan( false, false ) );
	$missing = 0;
	foreach ( array( 'create', 'fill', 'publish' ) as $action ) {
		$missing += isset( $counts[ $action ] ) ? $counts[ $action ] : 0;
	}
	if ( ! $missing ) {
		return;
	}

	printf(
		'<div class="notice notice-warning" id="osous-install-notice"><p>%s <a href="%s">%s</a></p></div>',
		/* translators: 1: how many pages are missing or empty, 2: how many pages the site has. */
		esc_html( sprintf( _n( '%1$d of the site’s %2$d pages is missing or empty.', '%1$d of the site’s %2$d pages are missing or empty.', $missing, 'osous' ), $missing, count( osous_install_data()['pages'] ) ) ),
		esc_url( admin_url( 'themes.php?page=osous-site-pages' ) ),
		esc_html__( 'Install the site’s pages', 'osous' )
	);
}
add_action( 'admin_notices', 'osous_install_notice' );

/**
 * `wp osous install-pages [--dry-run] [--replace-content] [--replace-menus]`
 *
 * The same as the button, from the command line; `env.sh rebuild` builds the local site
 * with it.
 *
 * @param array $args       Positional arguments; none.
 * @param array $assoc_args The flags.
 */
function osous_install_cli( $args, $assoc_args ) { // phpcs:ignore Generic.CodeAnalysis.UnusedFunctionParameter.FoundBeforeLastUsed -- WP-CLI's signature.
	$replace_content = ! empty( $assoc_args['replace-content'] );

	if ( ! empty( $assoc_args['dry-run'] ) ) {
		$pages = osous_install_plan( $replace_content );
		$notes = array();
		$label = osous_install_labels( false );
	} else {
		$report = osous_install_run(
			array(
				'replace_content' => $replace_content,
				'replace_menus'   => ! empty( $assoc_args['replace-menus'] ),
			)
		);
		$pages  = $report['pages'];
		$notes  = $report['notes'];
		$label  = osous_install_labels( true );
	}

	foreach ( $pages as $row ) {
		WP_CLI::log( sprintf( '%-34s %6s  %s', $row['key'], $row['id'] ? $row['id'] : '-', $label[ $row['action'] ] . ( empty( $row['error'] ) ? '' : ': ' . $row['error'] ) ) );
	}
	foreach ( $notes as $note ) {
		WP_CLI::log( $note );
	}

	$parts = array();
	foreach ( osous_install_counts( $pages ) as $action => $count ) {
		$parts[] = $action . ' ' . $count;
	}
	$summary = sprintf( '%d pages: %s', count( $pages ), implode( ', ', $parts ) );
	if ( isset( osous_install_counts( $pages )['failed'] ) ) {
		WP_CLI::error( $summary );
	}
	WP_CLI::success( $summary );
}

if ( defined( 'WP_CLI' ) && WP_CLI ) {
	WP_CLI::add_command(
		'osous install-pages',
		'osous_install_cli',
		array(
			'shortdesc' => 'Install the site’s pages, menus and contact form from the theme.',
			'synopsis'  => array(
				array(
					'type'     => 'flag',
					'name'     => 'dry-run',
					'optional' => true,
				),
				array(
					'type'     => 'flag',
					'name'     => 'replace-content',
					'optional' => true,
				),
				array(
					'type'     => 'flag',
					'name'     => 'replace-menus',
					'optional' => true,
				),
			),
		)
	);
}
