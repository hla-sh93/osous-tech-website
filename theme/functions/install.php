/**
 * Between two rounds: how far it has got, and the next round asked for at once.
 *
 * The form sends itself; without scripts it is a button to press.
 *
 * @param array $progress The rounds so far, and the options they were asked with.
 */
function osous_install_progress_screen( $progress ) {
	$counts  = osous_install_counts( $progress['pages'] );
	$waiting = isset( $counts['waiting'] ) ? $counts['waiting'] : 0;
	$total   = count( $progress['pages'] );
	?>
	<div class="wrap osous-site-pages">
		<h1><?php esc_html_e( 'Installing the site’s pages…', 'osous' ); ?></h1>
		<p id="osous-install-progress">
			<?php
			/* translators: 1: pages done so far, 2: all the pages. */
			echo esc_html( sprintf( __( '%1$d of %2$d pages done. The rest follow in a moment; leave this page open.', 'osous' ), $total - $waiting, $total ) );
			?>
		</p>
		<form method="post" action="<?php echo esc_url( admin_url( 'admin-post.php' ) ); ?>" id="osous-install-continue">
			<input type="hidden" name="action" value="osous_install_pages">
			<input type="hidden" name="continue" value="1">
			<?php if ( ! empty( $progress['options']['replace_content'] ) ) : ?>
				<input type="hidden" name="replace_content" value="1">
			<?php endif; ?>
